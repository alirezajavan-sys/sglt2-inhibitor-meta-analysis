# Meta-analysis of SGLT2 inhibitors on cardiovascular death or hospitalisation for heart failure
# -----------------------------------------------------------------------------------------------
# Run from the repository root:   Rscript analysis.R
# Writes tables to results/ and figures to figures/.

suppressPackageStartupMessages({
  library(metafor)
  library(knitr)
})
source("R/functions.R")
dir.create("figures", showWarnings = FALSE)
dir.create("results", showWarnings = FALSE)

d <- load_trials()
d <- d[order(d$population, d$year), ]

md <- character()
add <- function(...) md <<- c(md, ...)
add("# Results", "",
    sprintf("Generated by `analysis.R` with R %s and metafor %s. k = %d trials, %s randomised participants.",
            getRversion(), packageVersion("metafor"), nrow(d), format(sum(d$n_randomized), big.mark = ",")), "")

# ---- 1. Primary analysis: random-effects (REML) -------------------------------
m_re <- rma(yi, sei = sei, data = d, method = "REML", slab = trial)
m_fe <- rma(yi, sei = sei, data = d, method = "FE")
m_hk <- rma(yi, sei = sei, data = d, method = "REML", test = "knha")
pi_re <- predict(m_re, transf = exp)

add("## Primary analysis (all 13 trials)", "",
    sprintf("* Random-effects (REML) pooled HR: **%s**, p %s.", fmt_model(m_re),
            ifelse(m_re$pval < 0.001, "< 0.001", paste("=", fmt_p(m_re$pval)))),
    sprintf("* 95%% prediction interval for a new trial: %.2f–%.2f.", pi_re$pi.lb, pi_re$pi.ub),
    sprintf("* Heterogeneity: I² = %.0f%%, τ² = %.4f, Cochran's Q = %.1f (df = %d, p = %s).",
            m_re$I2, m_re$tau2, m_re$QE, m_re$k - 1, fmt_p(m_re$QEp)), "")

# ---- 2. Subgroups by trial population ----------------------------------------
m_sub <- rma(yi, sei = sei, mods = ~ population, data = d, method = "REML")
sub_tab <- do.call(rbind, lapply(levels(d$population), function(p) {
  s <- subset(d, population == p)
  m <- rma(yi, sei = sei, data = s, method = "REML")
  data.frame(Population = p, Trials = nrow(s), Participants = format(sum(s$n_randomized), big.mark = ","),
             `Pooled HR (95% CI)` = fmt_model(m), `I²` = sprintf("%.0f%%", m$I2),
             check.names = FALSE)
}))
write.csv(sub_tab, "results/subgroups.csv", row.names = FALSE)
add("## Subgroups by trial population", "", kable(sub_tab, format = "pipe", row.names = FALSE), "",
    sprintf("Test for subgroup differences (meta-regression): Q_M = %.2f, df = %d, p = %s.",
            m_sub$QM, m_sub$m, fmt_p(m_sub$QMp)), "")

# ---- 3. Sensitivity analyses ------------------------------------------------------
sens <- list(
  "Primary: random effects (REML), all trials" = m_re,
  "Fixed effect (inverse variance)" = m_fe,
  "Random effects with Hartung-Knapp-Sidik-Jonkman CI" = m_hk,
  "Strict definition only (first CV death or HHF)" =
    rma(yi, sei = sei, data = subset(d, strict_definition), method = "REML"),
  "Excluding sotagliflozin (dual SGLT1/2 inhibitor)" =
    rma(yi, sei = sei, data = subset(d, drug != "sotagliflozin"), method = "REML")
)
sens_tab <- data.frame(Analysis = names(sens),
                       Trials = sapply(sens, function(m) m$k),
                       `Pooled HR (95% CI)` = sapply(sens, fmt_model),
                       check.names = FALSE, row.names = NULL)
write.csv(sens_tab, "results/sensitivity.csv", row.names = FALSE)
add("## Sensitivity analyses", "", kable(sens_tab, format = "pipe", row.names = FALSE), "")

l1o <- leave1out(m_re, transf = exp)
l1o_tab <- data.frame(`Omitted trial` = d$trial,
                      `Pooled HR (95% CI)` = sprintf("%.2f (%.2f–%.2f)", l1o$estimate, l1o$ci.lb, l1o$ci.ub),
                      `I²` = sprintf("%.0f%%", l1o$I2), check.names = FALSE)
write.csv(l1o_tab, "results/leave_one_out.csv", row.names = FALSE)
add("## Leave-one-out", "", kable(l1o_tab, format = "pipe", row.names = FALSE), "")

# Small-study effects (interpret cautiously with k = 13)
eg <- regtest(m_re)
add("## Small-study effects", "",
    sprintf("Egger-type regression test: z = %.2f, p = %s (low power with 13 trials).", eg$zval, fmt_p(eg$pval)), "")

# ---- 4. Figures -------------------------------------------------------------------
pal <- c("Type 2 diabetes (CV outcome trials)" = "#1f6feb", "Chronic kidney disease" = "#bf8700", "Heart failure" = "#cf222e")

# Forest plot grouped by population, with subgroup summaries
groups <- levels(d$population)
k_per <- table(d$population)
gap <- 3
rows <- integer(0); headers <- integer(0); summaries <- integer(0)
y <- nrow(d) + gap * length(groups) + 1
for (g in groups) {
  headers <- c(headers, y)
  idx <- seq_len(k_per[g])
  rows <- c(rows, y - idx)
  summaries <- c(summaries, y - k_per[g] - 1)
  y <- y - k_per[g] - gap
}
png("figures/forest_plot.png", width = 2000, height = 2100, res = 220)
par(mar = c(4, 0, 1.5, 0))
forest(m_re, atransf = exp, at = log(c(0.4, 0.6, 0.8, 1, 1.25)), xlim = c(-4.6, 1.9),
       rows = rows, ylim = c(-1.5, max(headers) + 3),
       ilab = cbind(d$drug, format(d$n_randomized, big.mark = ",")), ilab.xpos = c(-2.55, -1.7),
       colout = pal[as.character(d$population)], cex = 0.75, header = c("Trial", "HR [95% CI]"),
       xlab = "Hazard ratio for CV death or HF hospitalisation (log scale)",
       mlab = sprintf("All trials, random effects (I² = %.0f%%)", m_re$I2), refline = 0)
text(c(-2.55, -1.7), max(headers) + 2, c("Drug", "N"), font = 2, cex = 0.75)
for (i in seq_along(groups)) {
  text(-4.6, headers[i], groups[i], pos = 4, font = 4, cex = 0.8, col = pal[groups[i]])
  ms <- rma(yi, sei = sei, data = subset(d, population == groups[i]), method = "REML")
  addpoly(ms, row = summaries[i], atransf = exp, cex = 0.75, col = pal[groups[i]],
          mlab = sprintf("Subgroup (I² = %.0f%%)", ms$I2))
}
text(-4.6, -1.4, sprintf("Test for subgroup differences: p = %s", fmt_p(m_sub$QMp)), pos = 4, cex = 0.7)
dev.off()

png("figures/funnel_plot.png", width = 1400, height = 1200, res = 200)
funnel(m_re, atransf = exp, at = log(c(0.5, 0.7, 1, 1.4)), xlab = "Hazard ratio (log scale)",
       back = "grey95", shade = "white", hlines = "grey80", pch = 19,
       col = pal[as.character(d$population)])
legend("bottomright", legend = names(pal), col = pal, pch = 19, cex = 0.7, bty = "n")
dev.off()

png("figures/leave_one_out.png", width = 1600, height = 1300, res = 200)
par(mar = c(4.5, 10, 2, 1))
ord <- order(l1o$estimate)
plot(l1o$estimate[ord], seq_along(ord), xlim = c(0.70, 0.84), pch = 19, col = "#1f6feb",
     yaxt = "n", ylab = "", xlab = "Pooled HR after omitting the trial", main = "Leave-one-out sensitivity")
segments(l1o$ci.lb[ord], seq_along(ord), l1o$ci.ub[ord], seq_along(ord), col = "#1f6feb")
axis(2, at = seq_along(ord), labels = d$trial[ord], las = 1, cex.axis = 0.75)
abline(v = exp(m_re$b[1]), lty = 2, col = "grey40")
dev.off()

writeLines(md, "results/results.md")
cat(md, sep = "\n")
